//! Emits `generated/names.rs`: the dense `Name` id for every element and
//! attribute name across all schema versions, with byte-slice lookup.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::schema::{Content, Particle, Schema, TypeRef};

pub struct Names {
    pub elements: Vec<String>,
    pub attributes: Vec<String>,
}

pub fn collect(schemas: &[Schema]) -> Names {
    let mut elements = BTreeSet::new();
    let mut attributes = BTreeSet::new();
    for schema in schemas {
        elements.insert(schema.root.clone());
        for ty in schema.types.values().chain(schema.extra_types.values()) {
            visit(&ty.content, &mut elements, &mut attributes);
            for a in &ty.attributes {
                attributes.insert(a.name.clone());
            }
        }
    }
    Names {
        elements: elements.into_iter().collect(),
        attributes: attributes.into_iter().collect(),
    }
}

fn visit(content: &Content, elements: &mut BTreeSet<String>, attributes: &mut BTreeSet<String>) {
    let parts = match content {
        Content::Sequence(p) | Content::Choice(p) => p,
        Content::Empty => return,
    };
    for p in parts {
        match p {
            Particle::Element { name, ty, .. } => {
                elements.insert(name.clone());
                if let TypeRef::Inline(inner) = ty {
                    visit(&inner.content, elements, attributes);
                    for a in &inner.attributes {
                        attributes.insert(a.name.clone());
                    }
                }
            }
            Particle::Group { content, .. } => visit(content, elements, attributes),
        }
    }
}

/// Upper camel case variants in sorted name order; `image` next to `Image`
/// becomes `ImageLower`, `CAD_ID` becomes `CADID`, attribute `ID` becomes
/// `AttrId`.
pub fn variants(names: &[String], prefix: &str) -> Vec<String> {
    let mut used = BTreeSet::new();
    let mut out = Vec::with_capacity(names.len());
    for name in names {
        let mut variant = format!("{prefix}{}", camel(name, !prefix.is_empty()));
        if used.contains(&variant) {
            variant.push_str("Lower");
        }
        used.insert(variant.clone());
        out.push(variant);
    }
    out
}

fn camel(name: &str, titlecase_all_upper: bool) -> String {
    let all_upper = titlecase_all_upper && name.chars().all(|c| c.is_uppercase());
    name.split('_')
        .filter(|segment| !segment.is_empty())
        .map(|segment| {
            let mut chars = segment.chars();
            let Some(first) = chars.next() else {
                return String::new();
            };
            let rest: String = match all_upper {
                true => chars.flat_map(char::to_lowercase).collect(),
                false => chars.collect(),
            };
            first.to_uppercase().chain(rest.chars()).collect()
        })
        .collect()
}

pub fn emit(names: &Names, sources: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by xtask gen from {sources}; do not edit."
    );
    let _ = writeln!(
        out,
        "//! Element and attribute names of GAEB DA XML as a dense id.\n"
    );
    let element_variants = variants(&names.elements, "");
    let attribute_variants = variants(&names.attributes, "Attr");
    let count = 1 + element_variants.len() + attribute_variants.len();
    let first_attr = 1 + element_variants.len();
    let _ = writeln!(
        out,
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    );
    let _ = writeln!(out, "#[repr(u16)]");
    let _ = writeln!(out, "pub enum Name {{");
    let _ = writeln!(out, "    Unknown = 0,");
    for v in element_variants.iter().chain(attribute_variants.iter()) {
        let _ = writeln!(out, "    {v},");
    }
    let _ = writeln!(out, "}}\n");
    let _ = writeln!(out, "impl Name {{");
    let _ = writeln!(out, "    pub const COUNT: usize = {count};");
    let _ = writeln!(out, "    const FIRST_ATTR: u16 = {first_attr};");
    let _ = writeln!(out, "    pub const ALL: [Name; {count}] = [");
    let _ = writeln!(out, "        Name::Unknown,");
    for v in element_variants.iter().chain(attribute_variants.iter()) {
        let _ = writeln!(out, "        Name::{v},");
    }
    let _ = writeln!(out, "    ];\n");
    let _ = writeln!(
        out,
        "    /// Whether this id names an attribute rather than an element."
    );
    let _ = writeln!(out, "    pub fn is_attr(self) -> bool {{");
    let _ = writeln!(out, "        self as u16 >= Self::FIRST_ATTR");
    let _ = writeln!(out, "    }}\n");
    let _ = writeln!(out, "    /// The XML name; empty for `Unknown`.");
    let _ = writeln!(out, "    pub fn as_str(self) -> &'static str {{");
    let _ = writeln!(out, "        match self {{");
    let _ = writeln!(out, "            Name::Unknown => \"\",");
    for (n, v) in names.elements.iter().zip(&element_variants) {
        let _ = writeln!(out, "            Name::{v} => \"{n}\",");
    }
    for (n, v) in names.attributes.iter().zip(&attribute_variants) {
        let _ = writeln!(out, "            Name::{v} => \"{n}\",");
    }
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}\n");
    emit_lookup(
        &mut out,
        "lookup",
        "The element with this name, or `Unknown`.",
        &names.elements,
        &element_variants,
    );
    out.push('\n');
    emit_lookup(
        &mut out,
        "lookup_attr",
        "The attribute with this name, or `Unknown`.",
        &names.attributes,
        &attribute_variants,
    );
    let _ = writeln!(out, "}}");
    out
}

fn emit_lookup(out: &mut String, function: &str, doc: &str, names: &[String], variants: &[String]) {
    let _ = writeln!(out, "    /// {doc}");
    let _ = writeln!(out, "    pub fn {function}(bytes: &[u8]) -> Name {{");
    let _ = writeln!(out, "        match bytes.len() {{");
    let mut lengths: Vec<usize> = names.iter().map(String::len).collect();
    lengths.sort_unstable();
    lengths.dedup();
    for len in lengths {
        let _ = writeln!(out, "            {len} => match bytes {{");
        for (n, v) in names.iter().zip(variants) {
            if n.len() != len {
                continue;
            }
            let _ = writeln!(out, "                b\"{n}\" => Name::{v},");
        }
        let _ = writeln!(out, "                _ => Name::Unknown,");
        let _ = writeln!(out, "            }},");
    }
    let _ = writeln!(out, "            _ => Name::Unknown,");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
}
