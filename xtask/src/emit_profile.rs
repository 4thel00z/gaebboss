//! Emits `generated/profile.rs`: per (version, phase) the elements each
//! type may and must carry, from the phase schemas' redefinitions.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::emit_names::variants;
use crate::merge::{Model, rust_type_name};
use crate::schema::{Schema, SchemaVersion};

pub fn emit(
    schemas: &[Schema],
    model: &Model,
    element_names: &[String],
    phases: &[String],
    sources: &str,
) -> String {
    let element_variants = variants(element_names, "");
    let variant = |name: &str| -> Option<String> {
        element_names
            .iter()
            .position(|n| n == name)
            .map(|i| element_variants[i].clone())
    };
    let names = |set: &BTreeSet<String>| -> String {
        set.iter()
            .filter_map(|n| variant(n))
            .map(|v| format!("Name::{v}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by xtask gen from {sources}; do not edit."
    );
    let _ = writeln!(
        out,
        "//! Phase profiles: what each type may and must carry per version and phase.\n"
    );
    let _ = writeln!(out, "use crate::name::Name;");
    let _ = writeln!(out, "use crate::version::{{Phase, Version}};\n");
    let _ = writeln!(out, "pub struct Restriction {{");
    let _ = writeln!(out, "    pub allowed: &'static [Name],");
    let _ = writeln!(out, "    pub required: &'static [Name],");
    let _ = writeln!(out, "}}\n");
    let mut arms = Vec::new();
    for schema in schemas {
        let version = match schema.version {
            SchemaVersion::V31 => continue,
            SchemaVersion::V32 => "V32",
            SchemaVersion::V33 => "V33",
        };
        for (code, profile) in &schema.profiles {
            if !phases.contains(code) {
                continue;
            }
            let phase = format!("X{}", code.replace('.', "_"));
            let table = format!("{version}_{phase}");
            let _ = writeln!(out, "static {table}: &[(&str, Restriction)] = &[");
            let mut emitted: Vec<String> = Vec::new();
            for (xsd_type, restriction) in &profile.restricted {
                let rust = rust_type_name(xsd_type);
                if !model.types.contains_key(&rust) {
                    continue;
                }
                emitted.push(rust.clone());
                let _ = writeln!(
                    out,
                    "    (\"{rust}\", Restriction {{ allowed: &[{}], required: &[{}] }}),",
                    names(&restriction.allowed),
                    names(&restriction.required)
                );
            }
            for (kept, other) in &model.aliases {
                if emitted.contains(kept) {
                    continue;
                }
                let Some(other_xsd) = model.types.get(other).map(|t| t.xsd.clone()) else {
                    continue;
                };
                let Some(restriction) = profile.restricted.get(&other_xsd) else {
                    continue;
                };
                emitted.push(kept.clone());
                let _ = writeln!(
                    out,
                    "    (\"{kept}\", Restriction {{ allowed: &[{}], required: &[{}] }}),",
                    names(&restriction.allowed),
                    names(&restriction.required)
                );
            }
            let _ = writeln!(out, "];\n");
            arms.push(format!(
                "        (Version::{version}, Phase::{phase}) => Some({table}),"
            ));
        }
    }
    let _ = writeln!(
        out,
        "/// The restrictions of a phase in a version, or `None` when that phase"
    );
    let _ = writeln!(out, "/// cannot be written in that version.");
    let _ = writeln!(
        out,
        "pub fn restrictions(version: Version, phase: Phase) -> Option<&'static [(&'static str, Restriction)]> {{"
    );
    let _ = writeln!(out, "    match (version, phase) {{");
    for arm in arms {
        let _ = writeln!(out, "{arm}");
    }
    let _ = writeln!(out, "        _ => None,");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    out
}
