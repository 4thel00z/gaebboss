//! Emits `generated/write.rs`: one writer per complex type that emits the
//! element in the target version's order, applying the phase profile.

use std::fmt::Write as _;

use crate::emit_names::variants;
use crate::emit_read::reader_name;
use crate::merge::{FieldKind, MField, MType, Model, Scalar};
use crate::schema::SchemaVersion;

pub fn writer_name(type_name: &str) -> String {
    reader_name(type_name).replacen("read_", "write_", 1)
}

pub fn emit(model: &Model, sources: &str, element_names: &[String]) -> String {
    let element_variants = variants(element_names, "");
    let variant = |name: &str| -> String {
        element_names
            .iter()
            .position(|n| n == name)
            .map(|i| element_variants[i].clone())
            .unwrap_or_else(|| "Unknown".to_string())
    };
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by xtask gen from {sources}; do not edit."
    );
    let _ = writeln!(
        out,
        "//! Writers from the typed model to XML, one per complex type.\n"
    );
    let _ = writeln!(out, "use crate::generated::model::*;");
    let _ = writeln!(out, "use crate::name::Name;");
    let _ = writeln!(out, "use crate::read::EnumValue;");
    let _ = writeln!(out, "use crate::version::Version;");
    let _ = writeln!(out, "use crate::write::{{WriteError, Writer}};\n");
    for ty in model.types.values() {
        if !ty.fields.is_empty() {
            emit_order(&mut out, ty, &variant);
            emit_field_writer(&mut out, ty, &variant);
        }
        emit_writer(&mut out, ty, &variant);
    }
    out
}

fn lower(name: &str) -> String {
    name.to_ascii_lowercase()
}

fn emit_order(out: &mut String, ty: &MType, variant: &dyn Fn(&str) -> String) {
    let _ = writeln!(
        out,
        "fn order_{}(version: Version) -> &'static [Name] {{",
        lower(&ty.name)
    );
    let writable: Vec<(&SchemaVersion, &Vec<String>)> = ty
        .order
        .iter()
        .filter(|(v, _)| **v != SchemaVersion::V31)
        .collect();
    if writable.is_empty() {
        let _ = writeln!(out, "    let _ = version;");
        let _ = writeln!(out, "    &[]");
        let _ = writeln!(out, "}}\n");
        return;
    }
    let _ = writeln!(out, "    match version {{");
    for (schema_version, names) in writable {
        let v = match schema_version {
            SchemaVersion::V31 => continue,
            SchemaVersion::V32 => "V32",
            SchemaVersion::V33 => "V33",
        };
        let list: Vec<String> = names
            .iter()
            .map(|n| format!("Name::{}", variant(n)))
            .collect();
        let _ = writeln!(out, "        Version::{v} => &[{}],", list.join(", "));
    }
    let _ = writeln!(out, "        _ => &[],");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

fn present(f: &MField) -> String {
    match f.many {
        true => format!("!value.{}.is_empty()", f.name),
        false => format!("value.{}.is_some()", f.name),
    }
}

/// Writes the next occurrence of one element of a type; returns whether
/// anything was written so callers can drain repeated fields.
fn emit_field_writer(out: &mut String, ty: &MType, variant: &dyn Fn(&str) -> String) {
    let name = &ty.name;
    let n = ty.fields.len();
    let _ = writeln!(
        out,
        "fn field_{}(w: &mut Writer<'_>, value: &{name}, name: Name, cursor: &mut [usize; {n}], restriction: Option<&'static crate::generated::profile::Restriction>) -> Result<bool, WriteError> {{",
        lower(name)
    );
    let _ = writeln!(out, "    match name {{");
    for (i, f) in ty.fields.iter().enumerate() {
        let v = variant(&f.element);
        let element = &f.element;
        let write_one = match &f.kind {
            FieldKind::Complex(t) => format!("{}(w, v, \"{element}\")?", writer_name(t)),
            FieldKind::Scalar(s) => {
                format!("w.{}(\"{element}\", {})", scalar_call(s), scalar_arg(s))
            }
        };
        let fetch = match (&f.kind, f.many, f.boxed) {
            (_, true, _) => format!("value.{}.get(cursor[{i}])", f.name),
            (FieldKind::Complex(_), false, true) => {
                format!("value.{}.as_deref().filter(|_| cursor[{i}] == 0)", f.name)
            }
            (_, false, _) => format!("value.{}.as_ref().filter(|_| cursor[{i}] == 0)", f.name),
        };
        let _ = writeln!(out, "        Name::{v} => {{");
        let _ = writeln!(
            out,
            "            let Some(v) = {fetch} else {{ return Ok(false) }};"
        );
        let _ = writeln!(out, "            cursor[{i}] += 1;");
        let _ = writeln!(out, "            if w.allowed(restriction, Name::{v}) {{");
        let _ = writeln!(out, "                {write_one};");
        let _ = writeln!(out, "            }} else {{");
        let _ = writeln!(out, "                w.dropped(\"{name}\", \"{element}\");");
        let _ = writeln!(out, "            }}");
        let _ = writeln!(out, "            Ok(true)");
        let _ = writeln!(out, "        }}");
    }
    let _ = writeln!(out, "        _ => Ok(false),");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

fn emit_writer(out: &mut String, ty: &MType, variant: &dyn Fn(&str) -> String) {
    let name = &ty.name;
    let n = ty.fields.len();
    let _ = writeln!(
        out,
        "pub fn {}(w: &mut Writer<'_>, value: &{name}, tag: &str) -> Result<(), WriteError> {{",
        writer_name(name)
    );
    if !ty.fields.is_empty() {
        let _ = writeln!(out, "    let restriction = w.restriction(\"{name}\");");
        let _ = writeln!(out, "    for required in w.required(restriction) {{");
        let _ = writeln!(out, "        let present = match required {{");
        for f in &ty.fields {
            let _ = writeln!(
                out,
                "            Name::{} => {},",
                variant(&f.element),
                present(f)
            );
        }
        let _ = writeln!(out, "            _ => true,");
        let _ = writeln!(out, "        }};");
        let _ = writeln!(out, "        if !present {{");
        let _ = writeln!(
            out,
            "            w.missing(\"{name}\", *required, value.node)?;"
        );
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "    w.open(tag);");
    for a in &ty.attrs {
        let call = match &a.scalar {
            Scalar::Span => "attr_span",
            Scalar::Decimal => "attr_decimal",
            Scalar::Integer => "attr_integer",
            Scalar::Bool => "attr_bool",
            Scalar::Enum(_) => "attr_enum",
        };
        let _ = writeln!(out, "    if let Some(v) = value.{} {{", a.name);
        let _ = writeln!(out, "        w.{call}(\"{}\", v);", a.attribute);
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "    w.open_end();");
    if ty.text.is_some() {
        let _ = writeln!(out, "    w.text(value.text);");
    }
    if !ty.fields.is_empty() {
        let _ = writeln!(out, "    let order = order_{}(w.version());", lower(name));
        let _ = writeln!(out, "    let mut cursor = [0usize; {n}];");
        if ty.ordered {
            let groups: Vec<String> = ty
                .groups
                .iter()
                .map(|g| {
                    format!(
                        "&[{}]",
                        g.iter()
                            .map(|n| format!("Name::{}", variant(n)))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                })
                .collect();
            let _ = writeln!(
                out,
                "    let groups: &[&[Name]] = &[{}];",
                groups.join(", ")
            );
            let _ = writeln!(
                out,
                "    let mut done = [false; {}];",
                ty.groups.len().max(1)
            );
            let _ = writeln!(out, "    for name in order {{");
            let _ = writeln!(
                out,
                "        let Some(g) = groups.iter().position(|g| g.contains(name)) else {{"
            );
            let _ = writeln!(
                out,
                "            while field_{}(w, value, *name, &mut cursor, restriction)? {{}}",
                lower(name)
            );
            let _ = writeln!(out, "            continue;");
            let _ = writeln!(out, "        }};");
            let _ = writeln!(out, "        if done[g] {{");
            let _ = writeln!(out, "            continue;");
            let _ = writeln!(out, "        }}");
            let _ = writeln!(out, "        done[g] = true;");
            let _ = writeln!(
                out,
                "        for child in value.children.iter().filter(|c| groups[g].contains(c)) {{"
            );
            let _ = writeln!(
                out,
                "            field_{}(w, value, *child, &mut cursor, restriction)?;",
                lower(name)
            );
            let _ = writeln!(out, "        }}");
            let _ = writeln!(
                out,
                "        for member in order.iter().filter(|m| groups[g].contains(m)) {{"
            );
            let _ = writeln!(
                out,
                "            while field_{}(w, value, *member, &mut cursor, restriction)? {{}}",
                lower(name)
            );
            let _ = writeln!(out, "        }}");
            let _ = writeln!(out, "    }}");
        } else {
            let _ = writeln!(out, "    for name in order {{");
            let _ = writeln!(
                out,
                "        while field_{}(w, value, *name, &mut cursor, restriction)? {{}}",
                lower(name)
            );
            let _ = writeln!(out, "    }}");
        }
        for (i, f) in ty.fields.iter().enumerate() {
            let remaining = match f.many {
                true => format!("value.{}.len() > cursor[{i}]", f.name),
                false => format!("value.{}.is_some() && cursor[{i}] == 0", f.name),
            };
            let _ = writeln!(out, "    if {remaining} {{");
            let _ = writeln!(out, "        w.dropped(\"{name}\", \"{}\");", f.element);
            let _ = writeln!(out, "    }}");
        }
    }
    let _ = writeln!(out, "    w.extra(&value.extra, \"{name}\");");
    let _ = writeln!(out, "    w.close(tag);");
    let _ = writeln!(out, "    Ok(())");
    let _ = writeln!(out, "}}\n");
}

fn scalar_call(s: &Scalar) -> &'static str {
    match s {
        Scalar::Span => "span_elem",
        Scalar::Decimal => "decimal_elem",
        Scalar::Integer => "integer_elem",
        Scalar::Bool => "bool_elem",
        Scalar::Enum(_) => "enum_elem",
    }
}

fn scalar_arg(s: &Scalar) -> &'static str {
    match s {
        Scalar::Enum(_) => "v.as_str()",
        _ => "*v",
    }
}
