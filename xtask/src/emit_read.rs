//! Emits `generated/read.rs`: one reader per complex type that walks a
//! tape node's attributes and children in a straight loop.

use std::fmt::Write as _;

use crate::emit_names::variants;
use crate::merge::{FieldKind, MType, Model, Scalar};

pub fn emit(
    model: &Model,
    sources: &str,
    element_names: &[String],
    attribute_names: &[String],
) -> String {
    let element_variants = variants(element_names, "");
    let attribute_variants = variants(attribute_names, "Attr");
    let element = |name: &str| -> String {
        element_names
            .iter()
            .position(|n| n == name)
            .map(|i| element_variants[i].clone())
            .unwrap_or_else(|| "Unknown".to_string())
    };
    let attribute = |name: &str| -> String {
        attribute_names
            .iter()
            .position(|n| n == name)
            .map(|i| attribute_variants[i].clone())
            .unwrap_or_else(|| "Unknown".to_string())
    };
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by xtask gen from {sources}; do not edit."
    );
    let _ = writeln!(
        out,
        "//! Readers from the tape into the typed model, one per complex type.\n"
    );
    let _ = writeln!(out, "use crate::generated::model::*;");
    let _ = writeln!(out, "use crate::name::Name;");
    let _ = writeln!(out, "use crate::read::Reader;");
    let _ = writeln!(out, "use crate::tape::NodeId;\n");
    for ty in model.types.values() {
        emit_reader(&mut out, ty, &element, &attribute);
    }
    out
}

pub fn reader_name(type_name: &str) -> String {
    format!("read_{}", type_name.to_ascii_lowercase())
}

fn emit_reader(
    out: &mut String,
    ty: &MType,
    element: &dyn Fn(&str) -> String,
    attribute: &dyn Fn(&str) -> String,
) {
    let _ = writeln!(
        out,
        "pub fn {}(r: &mut Reader<'_>, node: NodeId) -> {} {{",
        reader_name(&ty.name),
        ty.name
    );
    let _ = writeln!(
        out,
        "    let mut out = {} {{ node, ..Default::default() }};",
        ty.name
    );
    if ty.text.is_some() {
        let _ = writeln!(out, "    out.text = r.text(node);");
    }
    if !ty.attrs.is_empty() {
        let _ = writeln!(out, "    for i in 0..r.attr_count(node) {{");
        let _ = writeln!(out, "        let attr = r.attr_at(node, i);");
        let _ = writeln!(out, "        match attr.name {{");
        for a in &ty.attrs {
            let setter = match &a.scalar {
                Scalar::Span => "set_attr_span",
                Scalar::Decimal => "set_attr_decimal",
                Scalar::Integer => "set_attr_integer",
                Scalar::Bool => "set_attr_bool",
                Scalar::Enum(_) => "set_attr_enum",
            };
            let _ = writeln!(
                out,
                "            Name::{} => r.{setter}(&mut out.{}, node, attr),",
                attribute(&a.attribute),
                a.name
            );
        }
        let _ = writeln!(out, "            _ => r.unknown_attr(node, attr),");
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "    let mut child = r.first_child(node);");
    let _ = writeln!(out, "    while child != crate::tape::NONE {{");
    if ty.fields.is_empty() {
        let _ = writeln!(out, "        r.unexpected(&mut out.extra, node, child);");
        let _ = writeln!(out, "        child = r.next(child);");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "    out");
        let _ = writeln!(out, "}}\n");
        return;
    }
    let _ = writeln!(out, "        match r.name(child) {{");
    for f in &ty.fields {
        let variant = element(&f.element);
        let line = match (&f.kind, f.many, f.boxed) {
            (FieldKind::Complex(t), true, _) => {
                format!("out.{}.push({}(r, child)),", f.name, reader_name(t))
            }
            (FieldKind::Complex(t), false, true) => format!(
                "r.set_boxed(&mut out.{}, node, child, {}),",
                f.name,
                reader_name(t)
            ),
            (FieldKind::Complex(t), false, false) => format!(
                "r.set_complex(&mut out.{}, node, child, {}),",
                f.name,
                reader_name(t)
            ),
            (FieldKind::Scalar(s), true, _) => {
                format!("r.push_{}(&mut out.{}, child),", scalar_suffix(s), f.name)
            }
            (FieldKind::Scalar(s), false, _) => format!(
                "r.set_{}(&mut out.{}, node, child),",
                scalar_suffix(s),
                f.name
            ),
        };
        match ty.ordered {
            true => {
                let body = line.trim_end_matches(',');
                let _ = writeln!(out, "            Name::{variant} => {{");
                let _ = writeln!(out, "                out.children.push(Name::{variant});");
                let _ = writeln!(out, "                {body};");
                let _ = writeln!(out, "            }}");
            }
            false => {
                let _ = writeln!(out, "            Name::{variant} => {line}");
            }
        }
    }
    let _ = writeln!(
        out,
        "            _ => r.unexpected(&mut out.extra, node, child),"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "        child = r.next(child);");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    out");
    let _ = writeln!(out, "}}\n");
}

fn scalar_suffix(s: &Scalar) -> &'static str {
    match s {
        Scalar::Span => "span",
        Scalar::Decimal => "decimal",
        Scalar::Integer => "integer",
        Scalar::Bool => "bool",
        Scalar::Enum(_) => "enum",
    }
}
