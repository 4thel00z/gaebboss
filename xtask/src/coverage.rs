//! `cargo xtask coverage [--check]`: a report of every element of the
//! GAEB DA XML 3.3 library with how gaebboss treats it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use crate::merge::{FieldKind, Model};
use crate::schema::Schema;

const SEMANTIC_SOURCES: &[&str] = &[
    "boq.rs",
    "text.rs",
    "bid.rs",
    "validate.rs",
    "json.rs",
    "version.rs",
    "oz.rs",
];

/// The elements the hand-written layers mention, by field name or `Name`.
fn semantic_elements(repo: &Path, model: &Model) -> BTreeSet<String> {
    let mut sources = String::new();
    for file in SEMANTIC_SOURCES {
        sources.push_str(
            &std::fs::read_to_string(repo.join("crates/gaebboss-core/src").join(file))
                .unwrap_or_default(),
        );
    }
    let mut out = BTreeSet::new();
    for ty in model.types.values() {
        for f in &ty.fields {
            let by_field = format!(".{}", f.name);
            let by_name = format!(
                "Name::{}",
                crate::emit_names::variants(std::slice::from_ref(&f.element), "")[0]
            );
            if sources.contains(&by_field) || sources.contains(&by_name) {
                out.insert(f.element.clone());
            }
        }
    }
    out
}

pub fn render(repo: &Path, schema: &Schema, model: &Model) -> String {
    let semantic = semantic_elements(repo, model);
    let mut phases_by_element: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for (code, profile) in &schema.profiles {
        for restriction in profile.restricted.values() {
            for element in &restriction.allowed {
                phases_by_element
                    .entry(element.clone())
                    .or_default()
                    .insert(format!("X{code}"));
            }
        }
    }
    let mut rows: BTreeMap<String, (BTreeSet<String>, BTreeSet<String>)> = BTreeMap::new();
    for ty in model.types.values() {
        if !ty.versions.contains(&crate::schema::SchemaVersion::V33) {
            continue;
        }
        for f in &ty.fields {
            let entry = rows.entry(f.element.clone()).or_default();
            entry.0.insert(ty.xsd.clone());
            if let FieldKind::Complex(t) = &f.kind {
                entry.1.insert(t.clone());
            }
        }
    }
    let total = rows.len();
    let semantic_count = rows.keys().filter(|e| semantic.contains(*e)).count();
    let mut out = String::new();
    let _ = writeln!(out, "# Schema coverage");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "Generated by `cargo xtask coverage` from `standard/3.3/GAEB_DA_XML_Lib_3.3_2021-05.xsd`."
    );
    let _ = writeln!(
        out,
        "Every element the 3.3 library declares is read into the typed model and"
    );
    let _ = writeln!(
        out,
        "written back; this table says which ones the semantic layer (items,"
    );
    let _ = writeln!(out, "texts, bids, validation, JSON) also interprets.");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "| elements | read and written | interpreted by the semantic layer |"
    );
    let _ = writeln!(out, "|---|---|---|");
    let _ = writeln!(out, "| {total} | {total} | {semantic_count} |");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "| element | in types | semantic | restricted in phases |"
    );
    let _ = writeln!(out, "|---|---|---|---|");
    for (element, (types, _)) in &rows {
        let phases = phases_by_element
            .get(element)
            .map(|p| p.iter().cloned().collect::<Vec<_>>().join(" "))
            .unwrap_or_default();
        let mark = match semantic.contains(element) {
            true => "yes",
            false => "",
        };
        let _ = writeln!(
            out,
            "| `{element}` | {} | {mark} | {phases} |",
            types
                .iter()
                .map(|t| format!("`{t}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    out
}

pub fn run(repo: &Path, schema: &Schema, model: &Model, check: bool) -> Result<(), String> {
    let path = repo.join("docs/src/reference/coverage.md");
    let content = render(repo, schema, model);
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if current == content {
        return Ok(());
    }
    if check {
        return Err(format!(
            "{} is stale; run `cargo xtask coverage`",
            path.display()
        ));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    std::fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}
